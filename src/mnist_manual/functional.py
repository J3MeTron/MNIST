"""
Прямой проход: элементарные операции, собранные из тензорной арифметики.

Ни одного слоя из torch.nn здесь нет. Все, что используется, - это
сложение, умножение, exp, log, max, sum и матричное умножение.
Цель: чтобы каждую формулу можно было руками записать на бумаге.

Соглашения по формам (B - размер батча, D - число признаков, C - классов):
    x : (B, D)    признаки, для MNIST D = 784
    W : (D, C)    веса линейного слоя
    b : (C,)      смещения
    z : (B, C)    логиты, z = x @ W + b
    y : (B,)      int64, правильные метки классов
"""

from __future__ import annotations

import math

import torch


# --------------------------------------------------------------------------
# softmax и log_softmax
# --------------------------------------------------------------------------

def softmax(z: torch.Tensor) -> torch.Tensor:
    """
    softmax по последней оси: p_k = exp(z_k) / sum_j exp(z_j).

    Вычитание максимума (z - z.max()) не меняет результат математически:
        exp(z_k - m) / sum_j exp(z_j - m) = exp(z_k) / sum_j exp(z_j),
    потому что exp(-m) сокращается в числителе и знаменателе.
    Но численно это критично: exp(100) уже 2.7e43, а exp(800) = inf.
    После вычитания максимума наибольший показатель равен exp(0) = 1.

    keepdim=True оставляет ось размером 1, чтобы broadcasting вычел
    максимум строки из всех элементов этой строки.
    """
    z_shifted = z - z.max(dim=-1, keepdim=True).values
    exp_z = z_shifted.exp()
    return exp_z / exp_z.sum(dim=-1, keepdim=True)


def log_softmax(z: torch.Tensor) -> torch.Tensor:
    """
    log(softmax(z)) посчитанный устойчиво, без промежуточного softmax.

    log p_k = z_k - log sum_j exp(z_j)
            = (z_k - m) - log sum_j exp(z_j - m),  где m = max_j z_j

    Зачем отдельная функция, если есть softmax(z).log():
    при очень малом p_k получается log(0) = -inf и дальше NaN в градиенте.
    Здесь log от суммы берется от числа не меньше 1 (слагаемое с j = argmax
    дает ровно exp(0) = 1), поэтому -inf не возникает.
    """
    m = z.max(dim=-1, keepdim=True).values
    z_shifted = z - m
    return z_shifted - z_shifted.exp().sum(dim=-1, keepdim=True).log()


def log_softmax_naive(z: torch.Tensor) -> torch.Tensor:
    """
    Версия без вычитания максимума - ровно как в ноутбуке преподавателя.

    Оставлена специально для демонстрации: на логитах порядка 1 она дает
    тот же ответ, а на логитах порядка 1000 возвращает NaN. Сравнение
    двух версий есть в ноутбуке 02.
    """
    return z - z.exp().sum(dim=-1, keepdim=True).log()


# --------------------------------------------------------------------------
# функция потерь
# --------------------------------------------------------------------------

def nll(log_probs: torch.Tensor, y: torch.Tensor) -> torch.Tensor:
    """
    Negative log-likelihood по уже прологарифмированным вероятностям.

    L = -(1/B) * sum_n log p[n, y_n]

    Выражение log_probs[range(B), y] - это "продвинутая индексация":
    из каждой строки n берется ровно один элемент, номер которого
    задан меткой y_n. Результат - вектор длины B, а не матрица.

    Почему берем среднее, а не сумму: тогда шаг обучения lr не зависит
    от размера батча. При сумме градиент пропорционален B и lr пришлось
    бы подбирать заново при каждой смене batch_size.
    """
    batch_size = y.shape[0]
    return -log_probs[range(batch_size), y].mean()


def cross_entropy(z: torch.Tensor, y: torch.Tensor) -> torch.Tensor:
    """
    Перекрестная энтропия прямо от логитов: nll(log_softmax(z), y).

    Это то же самое, что torch.nn.functional.cross_entropy. Разделение
    на два шага (log_softmax, затем nll) оставлено потому, что именно так
    устроен ноутбук преподавателя, и потому что градиент удобнее выводить
    через промежуточные логиты.
    """
    return nll(log_softmax(z), y)


# --------------------------------------------------------------------------
# нелинейность
# --------------------------------------------------------------------------

def relu(z: torch.Tensor) -> torch.Tensor:
    """
    ReLU: max(0, z), поэлементно.

    Реализовано через clamp, чтобы не вызывать torch.relu и было видно,
    что это просто обрезка снизу нулем.
    """
    return z.clamp(min=0.0)


def relu_mask(z: torch.Tensor) -> torch.Tensor:
    """
    Производная ReLU по ее входу: 1 там, где z > 0, иначе 0.

    В точке z = 0 производной формально нет. Договоренность (и в PyTorch,
    и здесь) - считать ее нулем. На обучение это не влияет: попадание
    ровно в нуль на float32 практически невероятно.

    Возвращаем float того же типа, что z, чтобы маску можно было
    умножать на градиент без приведения типов.
    """
    return (z > 0).to(z.dtype)


# --------------------------------------------------------------------------
# метрика и вспомогательное
# --------------------------------------------------------------------------

def accuracy(z: torch.Tensor, y: torch.Tensor) -> torch.Tensor:
    """
    Доля правильных ответов.

    argmax по логитам и по вероятностям дает один и тот же класс:
    softmax монотонно возрастает, порядок элементов не меняется.
    Поэтому softmax для предсказания считать не нужно.

    (preds == y) дает тензор из True/False; .float().mean() превращает
    его в долю - среднее от нулей и единиц.
    """
    preds = torch.argmax(z, dim=1)
    return (preds == y).to(torch.float32).mean()


def one_hot(y: torch.Tensor, num_classes: int = 10) -> torch.Tensor:
    """
    Метки -> матрица (B, C) из нулей с единицей в столбце правильного класса.

    В прямом проходе one-hot не нужен (хватает индексации в nll), но он
    нужен, чтобы записать аналитический градиент как (softmax(z) - Y) / B.
    """
    batch_size = y.shape[0]
    out = torch.zeros(batch_size, num_classes, dtype=torch.float32, device=y.device)
    out[range(batch_size), y] = 1.0
    return out


def init_linear(
    n_in: int,
    n_out: int,
    generator: torch.Generator | None = None,
    requires_grad: bool = True,
) -> tuple[torch.Tensor, torch.Tensor]:
    """
    Инициализация весов линейного слоя: W ~ N(0, 1) / sqrt(n_in), b = 0.

    Деление на sqrt(n_in) - это инициализация Ксавье в упрощенном виде,
    та же, что в ноутбуке преподавателя. Смысл: в z = sum_i x_i * W_i
    складываются n_in слагаемых. Для независимых слагаемых дисперсия
    суммы равна сумме дисперсий, то есть растет как n_in, а разброс -
    как sqrt(n_in). Если это не скомпенсировать, логиты на входе
    получаются огромными, softmax вырождается в почти-ноль и почти-единицу,
    и градиент становится крошечным - обучение стоит на месте.

    Смещения с нуля: асимметрию по классам модель доберет сама, случайный
    сдвиг здесь ничего не дает.

    requires_grad=True помечает тензор как обучаемый параметр - с этого
    момента PyTorch начинает записывать все операции с ним в граф,
    чтобы потом посчитать градиент в .backward().
    """
    w = torch.randn(n_in, n_out, generator=generator) / math.sqrt(n_in)
    b = torch.zeros(n_out)

    if requires_grad:
        w.requires_grad_()
        b.requires_grad_()

    return w, b
